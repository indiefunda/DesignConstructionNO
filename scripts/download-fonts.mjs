/**
 * Downloads the two typefaces we use (EB Garamond + Manrope) as self-hosted
 * woff2 subsets and writes @font-face rules. Self-hosting keeps the site free
 * of third-party requests — faster, and no cookie/privacy surface.
 *
 * Subsets requested: latin, latin-ext (å ø æ), greek, greek-ext.
 */
import fs from 'node:fs/promises';
import path from 'node:path';

const OUT = 'public/fonts';
const CSS_OUT = 'src/styles/fonts.css';
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';

const families = [
  {
    file: 'ebgaramond',
    query: 'EB+Garamond:ital,wght@0,400..700;1,400..500',
    subsets: ['latin', 'latin-ext', 'greek', 'greek-ext'],
  },
  {
    file: 'manrope',
    query: 'Manrope:wght@200..800',
    subsets: ['latin', 'latin-ext', 'greek'],
  },
];

await fs.mkdir(OUT, { recursive: true });
await fs.mkdir(path.dirname(CSS_OUT), { recursive: true });

let css = `/* Generated by scripts/download-fonts.mjs — do not edit by hand. */\n`;

for (const family of families) {
  const url = `https://fonts.googleapis.com/css2?family=${family.query}&display=swap`;
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`Google Fonts ${res.status} for ${family.query}`);
  const text = await res.text();

  // Each @font-face is preceded by a /* subset */ comment.
  const blockRe = /\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*\{([^}]+)\}/g;
  let match;
  let written = 0;

  while ((match = blockRe.exec(text))) {
    const [, subset, body] = match;
    if (!family.subsets.includes(subset)) continue;

    const style = /font-style:\s*([a-z]+)/.exec(body)?.[1] ?? 'normal';
    const weight = /font-weight:\s*([\d\s]+)/.exec(body)?.[1]?.trim() ?? '400';
    const src = /url\((https:[^)]+)\)/.exec(body)?.[1];
    const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1]?.trim();
    if (!src) continue;

    const name = `${family.file}-${subset}-${style === 'italic' ? 'italic' : weight.replace(/\s+/g, '-')}.woff2`;
    const buf = Buffer.from(await (await fetch(src, { headers: { 'User-Agent': UA } })).arrayBuffer());
    await fs.writeFile(path.join(OUT, name), buf);

    const familyName = family.file === 'ebgaramond' ? 'EB Garamond' : 'Manrope';
    css += `@font-face{font-family:'${familyName}';font-style:${style};font-weight:${weight};font-display:swap;src:url('/fonts/${name}') format('woff2')${range ? `;unicode-range:${range}` : ''}}\n`;
    written += 1;
    console.log(`  ${name} ${(buf.length / 1024).toFixed(1)} kB`);
  }

  console.log(`${family.file}: ${written} faces`);
}

await fs.writeFile(CSS_OUT, css);
console.log(`wrote ${CSS_OUT}`);
